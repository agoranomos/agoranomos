def empty_settings(path: Path) -> list[str]:
    """The settings of an env file that have no value: the secrets that init generates."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return [line[:-1] for line in lines if re.fullmatch(r"[A-Z][A-Z0-9_]*=", line)]


# The secrets come from .env.example, not from a copy of its list, so a secret that is added there
# must be generated by init. test_env_example_has_twelve_secrets says how many there should be.
SECRET_KEYS = empty_settings(REPO_ROOT / ".env.example")

# The ways the script can learn that a port is in use: what a test passes to Cli.run to make it
# ask one tool, in one of the formats of the netstat stand-in.
PORT_TOOLS = {
    "ss": {"AGORANOMOS_PORT_TOOLS": "ss"},
    "netstat-bsd": {"AGORANOMOS_PORT_TOOLS": "netstat"},
    "netstat-linux": {"AGORANOMOS_PORT_TOOLS": "netstat", "FAKE_NETSTAT_STYLE": "linux"},
    "lsof": {"AGORANOMOS_PORT_TOOLS": "lsof"},
}


@pytest.fixture(params=list(PORT_TOOLS))
def port_tool(request):
    return PORT_TOOLS[request.param]


def check_limit(result, outcome, word):
    """A check of a resource ends in a stop, a warning or silence, in the lines that name word."""
    named = [line.split(":")[0] for line in result.stderr.splitlines() if word in line]
    assert result.returncode == (1 if outcome == "stop" else 0), result.stderr
    assert named == {"stop": ["error"], "warn": ["warning"], "pass": []}[outcome]


